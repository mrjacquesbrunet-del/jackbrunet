/** Numéro Strong d'un mot d'étude, ou null si on n'en est pas certain. */
export function numeroStrong(translit?: string, mot?: string): string | null {
  if (translit) {
    const n = TABLE[cle(translit)];
    if (n) return n;
  }
  if (mot) {
    const n = TABLE[cle(mot)];
    if (n) return n;
  }
  return null;
}
